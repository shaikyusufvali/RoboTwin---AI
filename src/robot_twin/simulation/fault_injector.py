"""Fault injection models for RoboTwin-AI simulation.

The injector creates controlled and observable fault signatures for
synthetic robot telemetry generation.

These scenarios are simulation models for AI development and validation.
They are not physical robot failure models.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Final

import pybullet as p

from robot_twin.simulation.robot_simulator import RobotSimulator


class FaultType(str, Enum):
    """Supported simulated fault types."""

    NORMAL = "normal"
    MOTOR_RESISTANCE = "motor_resistance"
    LOW_MOTOR_POWER = "low_motor_power"
    POSITION_DRIFT = "position_drift"


@dataclass(frozen=True)
class FaultScenario:
    """Configuration for one simulated fault scenario."""

    fault_type: FaultType
    joint_index: int = 2
    severity: float = 0.5


@dataclass(frozen=True)
class FaultTelemetry:
    """Synthetic telemetry signature generated by a fault."""

    target_position: float
    fault_load: float


class FaultInjector:
    """Apply controlled fault behavior to a simulated robot joint."""

    DEFAULT_TARGET_POSITION: Final[float] = 0.8

    MAX_MOTOR_FORCE: Final[float] = 80.0

    MOTOR_RESISTANCE_MIN_FORCE: Final[float] = 45.0
    MOTOR_RESISTANCE_FORCE_REDUCTION: Final[float] = 0.35
    MOTOR_RESISTANCE_MAX_TARGET_OFFSET: Final[float] = 0.30
    MOTOR_RESISTANCE_MAX_FAULT_LOAD: Final[float] = 2.5

    LOW_POWER_MIN_FORCE: Final[float] = 4.0
    LOW_POWER_FORCE_REDUCTION: Final[float] = 0.90
    LOW_POWER_TARGET_SCALE: Final[float] = 0.45
    LOW_POWER_MAX_FAULT_LOAD: Final[float] = 1.5

    POSITION_DRIFT_MAX_OFFSET: Final[float] = 0.35
    POSITION_DRIFT_MAX_FAULT_LOAD: Final[float] = 0.5

    POSITION_GAIN: Final[float] = 0.8
    VELOCITY_GAIN: Final[float] = 0.3

    def __init__(
        self,
        simulator: RobotSimulator,
    ) -> None:
        self._simulator = simulator
        self._fault_telemetry: dict[int, FaultTelemetry] = {}

    def apply(
        self,
        scenario: FaultScenario,
    ) -> None:
        """Apply the selected fault scenario."""

        self._validate_scenario(scenario)

        if scenario.fault_type == FaultType.NORMAL:
            self._apply_normal(scenario)
            return

        if scenario.fault_type == FaultType.MOTOR_RESISTANCE:
            self._apply_motor_resistance(scenario)
            return

        if scenario.fault_type == FaultType.LOW_MOTOR_POWER:
            self._apply_low_motor_power(scenario)
            return

        if scenario.fault_type == FaultType.POSITION_DRIFT:
            self._apply_position_drift(scenario)
            return

        raise ValueError(
            f"Unsupported fault type: {scenario.fault_type}"
        )

    def get_fault_telemetry(
        self,
        joint_index: int,
    ) -> FaultTelemetry:
        """Return the current synthetic fault signature for a joint."""

        if joint_index < 0:
            raise ValueError(
                "joint_index must be non-negative."
            )

        return self._fault_telemetry.get(
            joint_index,
            FaultTelemetry(
                target_position=self.DEFAULT_TARGET_POSITION,
                fault_load=0.0,
            ),
        )

    def get_fault_load(
        self,
        joint_index: int,
    ) -> float:
        """Return the current synthetic fault load for a joint."""

        return self.get_fault_telemetry(
            joint_index
        ).fault_load

    def get_target_position(
        self,
        joint_index: int,
    ) -> float:
        """Return the intended target position for a joint."""

        return self.get_fault_telemetry(
            joint_index
        ).target_position

    def clear(
        self,
        joint_index: int,
    ) -> None:
        """Clear the injected fault signature for a joint."""

        if joint_index < 0:
            raise ValueError(
                "joint_index must be non-negative."
            )

        self._fault_telemetry.pop(
            joint_index,
            None,
        )

    def clear_all(self) -> None:
        """Clear all stored fault signatures."""

        self._fault_telemetry.clear()

    def _apply_normal(
        self,
        scenario: FaultScenario,
    ) -> None:
        """Apply nominal motor behavior."""

        target_position = self.DEFAULT_TARGET_POSITION

        self._set_position_control(
            joint_index=scenario.joint_index,
            target_position=target_position,
            force=self.MAX_MOTOR_FORCE,
        )

        self._fault_telemetry[
            scenario.joint_index
        ] = FaultTelemetry(
            target_position=target_position,
            fault_load=0.0,
        )

    def _apply_motor_resistance(
        self,
        scenario: FaultScenario,
    ) -> None:
        """Simulate bounded mechanical resistance.

        Mechanical resistance is represented by reducing available
        actuator force and introducing a controlled target offset.

        No external torque is injected because uncontrolled external
        torques can create unstable simulation behavior.
        """

        severity = scenario.severity

        available_force = (
            self.MAX_MOTOR_FORCE
            * (
                1.0
                - self.MOTOR_RESISTANCE_FORCE_REDUCTION
                * severity
            )
        )

        available_force = max(
            self.MOTOR_RESISTANCE_MIN_FORCE,
            available_force,
        )

        target_offset = (
            self.MOTOR_RESISTANCE_MAX_TARGET_OFFSET
            * severity
        )

        effective_target = (
            self.DEFAULT_TARGET_POSITION
            - target_offset
        )

        fault_load = (
            self.MOTOR_RESISTANCE_MAX_FAULT_LOAD
            * severity
        )

        self._set_position_control(
            joint_index=scenario.joint_index,
            target_position=effective_target,
            force=available_force,
        )

        self._fault_telemetry[
            scenario.joint_index
        ] = FaultTelemetry(
            target_position=self.DEFAULT_TARGET_POSITION,
            fault_load=fault_load,
        )

    def _apply_low_motor_power(
        self,
        scenario: FaultScenario,
    ) -> None:
        """Simulate reduced actuator power."""

        severity = scenario.severity

        available_force = (
            self.MAX_MOTOR_FORCE
            * (
                1.0
                - self.LOW_POWER_FORCE_REDUCTION
                * severity
            )
        )

        available_force = max(
            self.LOW_POWER_MIN_FORCE,
            available_force,
        )

        effective_target = (
            self.DEFAULT_TARGET_POSITION
            * (
                1.0
                - self.LOW_POWER_TARGET_SCALE
                * severity
            )
        )

        fault_load = (
            self.LOW_POWER_MAX_FAULT_LOAD
            * severity
        )

        self._set_position_control(
            joint_index=scenario.joint_index,
            target_position=effective_target,
            force=available_force,
        )

        self._fault_telemetry[
            scenario.joint_index
        ] = FaultTelemetry(
            target_position=self.DEFAULT_TARGET_POSITION,
            fault_load=fault_load,
        )

    def _apply_position_drift(
        self,
        scenario: FaultScenario,
    ) -> None:
        """Simulate position-control or feedback drift."""

        severity = scenario.severity

        drift = (
            self.POSITION_DRIFT_MAX_OFFSET
            * severity
        )

        effective_target = (
            self.DEFAULT_TARGET_POSITION
            + drift
        )

        fault_load = (
            self.POSITION_DRIFT_MAX_FAULT_LOAD
            * severity
        )

        self._set_position_control(
            joint_index=scenario.joint_index,
            target_position=effective_target,
            force=self.MAX_MOTOR_FORCE,
        )

        self._fault_telemetry[
            scenario.joint_index
        ] = FaultTelemetry(
            target_position=self.DEFAULT_TARGET_POSITION,
            fault_load=fault_load,
        )

    def _set_position_control(
        self,
        joint_index: int,
        target_position: float,
        force: float,
    ) -> None:
        """Apply position control to the simulated robot joint."""

        p.setJointMotorControl2(
            bodyUniqueId=self._simulator.robot_id,
            jointIndex=joint_index,
            controlMode=p.POSITION_CONTROL,
            targetPosition=target_position,
            positionGain=self.POSITION_GAIN,
            velocityGain=self.VELOCITY_GAIN,
            force=force,
            physicsClientId=self._simulator.client_id,
        )

    @staticmethod
    def _validate_scenario(
        scenario: FaultScenario,
    ) -> None:
        """Validate fault scenario parameters."""

        if not isinstance(
            scenario,
            FaultScenario,
        ):
            raise TypeError(
                "scenario must be a FaultScenario instance."
            )

        if not isinstance(
            scenario.fault_type,
            FaultType,
        ):
            raise TypeError(
                "fault_type must be a FaultType instance."
            )

        if not isinstance(
            scenario.joint_index,
            int,
        ):
            raise TypeError(
                "joint_index must be an integer."
            )

        if scenario.joint_index < 0:
            raise ValueError(
                "joint_index must be non-negative."
            )

        if not 0.0 <= scenario.severity <= 1.0:
            raise ValueError(
                "severity must be between 0.0 and 1.0."
            )


def main() -> None:
    """Run a basic fault-injection demonstration."""

    import logging

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(message)s",
    )

    with RobotSimulator() as simulator:
        injector = FaultInjector(simulator)

        scenario = FaultScenario(
            fault_type=FaultType.MOTOR_RESISTANCE,
            joint_index=2,
            severity=0.7,
        )

        for _ in range(240):
            injector.apply(scenario)
            simulator.step()

        telemetry = injector.get_fault_telemetry(
            joint_index=2
        )

        print()
        print("ROBOTWIN-AI FAULT INJECTION")
        print("=" * 60)
        print(
            f"Fault type       : "
            f"{scenario.fault_type.value}"
        )
        print(
            f"Joint             : "
            f"{scenario.joint_index}"
        )
        print(
            f"Severity          : "
            f"{scenario.severity:.2f}"
        )
        print(
            f"Target position   : "
            f"{telemetry.target_position:.4f} rad"
        )
        print(
            f"Synthetic load    : "
            f"{telemetry.fault_load:.4f}"
        )


if __name__ == "__main__":
    main()